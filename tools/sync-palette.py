#!/usr/bin/env python3
"""Regenerate _data/schemes.yml from the desktop's own resolved palette.

The site paints itself in the same colors wlRIX paints the desktop, so the
color values must not be transcribed by hand -- they would drift the first
time somebody retunes a role. wlrix-ui/src/palette/generated.rs is the last
point in the chain where the roles are fully resolved (the palette JSON still
carries derivations like `shadow(buttonBackground, top)`, and reimplementing
that color math here would be a second copy of it to keep correct). So this
reads the resolved statics and emits them as Jekyll data.

Usage:

    tools/sync-palette.py                    # default source path, in place
    tools/sync-palette.py --source PATH --output PATH

Re-running it on an unchanged source is a no-op; the output is deterministic.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

# The site renders in these two only. Adding a scheme here is enough to get its
# variables emitted; picking it up in CSS is a separate change in style.scss.
SCHEMES = ("CLASSIC", "GOTHAM")

HERE = Path(__file__).resolve().parent
SITE = HERE.parent
DEFAULT_SOURCE = SITE.parent / "wlrix-epoch/wlrix-ui/src/palette/generated.rs"
DEFAULT_OUTPUT = SITE / "_data/schemes.yml"

# `    face_top_shadow: Rgb(0xff_e5e5e5),` -- the alpha byte is always ff and is
# dropped, since CSS wants #rrggbb.
ROLE = re.compile(r"^\s{4}(\w+):\s*Rgb\(0x[0-9a-f]{2}_([0-9a-f]{6})\),\s*$")
# `    dark: true,`
FLAG = re.compile(r"^\s{4}(id|name|gamma|dark):\s*(.+?),\s*$")


def parse(source: str, scheme: str) -> dict[str, str]:
    """Pull one `pub static <scheme>: Palette = Palette { ... };` block out of the source."""
    start = source.find(f"pub static {scheme}: Palette = Palette {{")
    if start < 0:
        sys.exit(f"sync-palette: no `pub static {scheme}` in the source")
    end = source.find("\n};", start)
    if end < 0:
        sys.exit(f"sync-palette: `pub static {scheme}` is not terminated")

    roles: dict[str, str] = {}
    for line in source[start:end].splitlines()[1:]:
        if match := ROLE.match(line):
            roles[match.group(1).replace("_", "-")] = "#" + match.group(2)
        elif match := FLAG.match(line):
            roles[match.group(1)] = match.group(2).strip('"')

    if "panel" not in roles:
        sys.exit(f"sync-palette: {scheme} parsed without a `panel` role; the format has moved")
    return roles


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    if not args.source.exists():
        sys.exit(
            f"sync-palette: {args.source} not found.\n"
            "The site expects a wlrix-epoch checkout beside it; pass --source otherwise."
        )
    source = args.source.read_text(encoding="utf-8")

    lines = [
        "# GENERATED by tools/sync-palette.py. Do not edit.",
        "#",
        "# Source: wlrix-ui/src/palette/generated.rs, itself generated by",
        "# wlrix-assets/tools/palettegen from wlrix-assets/palette/*.json.",
        "# Re-run tools/sync-palette.py after the desktop's palette changes.",
        "#",
        "# Every key becomes a --wlrix-<key> custom property in assets/css/style.scss.",
        "",
    ]
    for scheme in SCHEMES:
        roles = parse(source, scheme)
        lines.append(f"{roles.pop('id')}:")
        for key, value in roles.items():
            # Everything but `dark` is quoted. A bare #rrggbb starts a YAML
            # comment, and a bare 1.7 gamma would come back as a float.
            lines.append(f"  {key}: {value}" if key == "dark" else f'  {key}: "{value}"')
        lines.append("")

    args.output.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
    print(f"sync-palette: wrote {args.output.relative_to(SITE)} from {args.source}")


if __name__ == "__main__":
    main()
